const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('cocoa', {
  onState: fn => ipcRenderer.on('state', (_, s) => fn(s)),
  onToast: fn => ipcRenderer.on('toast', (_, m) => fn(m)),
  importDialog: () => ipcRenderer.invoke('import-dialog'),
  importFiles: files => ipcRenderer.invoke('import-paths', [...files].map(f => webUtils.getPathForFile(f)).filter(Boolean)),
  saveLink: url => ipcRenderer.invoke('save-link', url),
  setDuration: (id, d) => ipcRenderer.invoke('set-duration', id, d),
  setPinned: on => ipcRenderer.invoke('set-pinned', on),
  setMini: on => ipcRenderer.invoke('set-mini', on),
  close: () => ipcRenderer.invoke('close'),
  createPlaylist: name => ipcRenderer.invoke('playlist-create', name),
  trackMenu: (id, playlistId) => ipcRenderer.invoke('track-menu', id, playlistId),
  playlistMenu: id => ipcRenderer.invoke('playlist-menu', id),
  appMenu: () => ipcRenderer.invoke('app-menu'),
  minimize: () => ipcRenderer.invoke('minimize'),
  setTheme: t => ipcRenderer.invoke('set-theme', t),
  onOpenSettings: fn => ipcRenderer.on('open-settings', () => fn()),
  createShortcuts: opts => ipcRenderer.invoke('create-shortcuts', opts),
  dismissWelcome: () => ipcRenderer.invoke('dismiss-welcome'),
  onOpenCloudImport: fn => ipcRenderer.on('open-cloud-import', () => fn()),
  cloud: {
    connect: p => ipcRenderer.invoke('cloud-connect', p),
    signOut: p => ipcRenderer.invoke('cloud-signout', p),
    use: p => ipcRenderer.invoke('cloud-use', p),
    set: o => ipcRenderer.invoke('cloud-set', o),
    folderGoogle: () => ipcRenderer.invoke('cloud-folder-google'),
    folderSet: f => ipcRenderer.invoke('cloud-folder-set', f),
    list: (p, dir) => ipcRenderer.invoke('cloud-list', p, dir),
    add: (p, files) => ipcRenderer.invoke('cloud-add', p, files),
    pickGoogle: () => ipcRenderer.invoke('cloud-pick-google'),
    moveAll: () => ipcRenderer.invoke('cloud-move-all'),
    sync: () => ipcRenderer.invoke('cloud-sync'),
  },
});
